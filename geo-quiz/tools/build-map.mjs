// Generates ../map-data.js: world country outlines as pre-projected SVG paths.
// Usage: npm i world-atlas@2.0.2 d3-geo@3 topojson-client@3 && node build-map.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoNaturalEarth1, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = require("world-atlas/countries-110m.json");
const W = 1000, H = 520;

const world = feature(topo, topo.objects.countries);
world.features = world.features.filter(f => f.id !== "010"); // drop Antarctica

const projection = geoNaturalEarth1().fitExtent([[6, 6], [W - 6, H - 6]], world);
const path = geoPath(projection);
const r = n => Math.round(n * 10) / 10;

const countries = world.features.map(f => {
  const d = path(f).replace(/-?\d+\.\d+/g, m => String(r(+m)));
  const [[x0, y0], [x1, y1]] = path.bounds(f);
  const [cx, cy] = path.centroid(f);
  return { id: f.id || f.properties.name, d, b: [x0, y0, x1, y1].map(r), c: [r(cx), r(cy)], a: Math.round(path.area(f)) };
});

writeFileSync(new URL("../map-data.js", import.meta.url),
  "// Generated by tools/build-map.mjs from Natural Earth 1:110m (world-atlas@2.0.2). Do not edit.\n" +
  `window.WORLD_MAP = ${JSON.stringify({ w: W, h: H, countries })};\n`);
console.log(countries.length, "countries");
